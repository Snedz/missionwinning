import { EXERCISES } from '@/data/exercises';
import { equipmentMatches } from '@/lib/coach/equipment';

const profiles = ['bodyweight', 'dumbbells', 'full-gym'] as const;
const groups = ['Chest', 'Back', 'Legs', 'Shoulders', 'Arms', 'Core'];

const rows = EXERCISES.flatMap((exercise) => {
  if (exercise.level && exercise.level !== 'beginner') return [];
  const primary = exercise.muscleGroups.find((group) => groups.includes(group));
  if (!primary) return [];
  const equipment = profiles.reduce((mask, profile, index) =>
    mask | (equipmentMatches(exercise, profile) ? 1 << index : 0), 0);
  return [[
    exercise.id,
    exercise.name,
    groups.indexOf(primary),
    equipment,
    exercise.muscleGroups.length >= 2 ? 1 : 0,
    exercise.tags?.includes('strength') ? 1 : 0,
    !exercise.equipment || exercise.equipment.toLowerCase().startsWith('bodyweight') ? 1 : 0,
  ].join('|')];
});

process.stdout.write(`package com.missionwinning.core.model

// Generated by apps/android/scripts/generate-offline-coach-catalog.ts.
object OfflineCoachCatalog {
    val moves: List<OfflineCoachMove> = """
${rows.join('\n')}
    """.trim().lineSequence().map { row ->
        val fields = row.split('|')
        OfflineCoachMove(
            id = fields[0],
            name = fields[1],
            primary = fields[2].toInt(),
            equipmentMask = fields[3].toInt(),
            compound = fields[4] == "1",
            strength = fields[5] == "1",
            bodyweight = fields[6] == "1",
        )
    }.toList()

    val byId: Map<String, OfflineCoachMove> = moves.associateBy { it.id }
}
`);
