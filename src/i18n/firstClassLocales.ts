export function firstClassOverlayFor(lang: string): Record<string, string> {
  const ui = normalizeUiLang(lang);
  if (OVERLAYS[ui]) return OVERLAYS[ui];
  const pack = packLangForUi(ui);
  return OVERLAYS[pack] ?? { ...EN };
}

export function applyFirstClassOverlay(
  target: Record<string, string>,
  lang: string
): Record<string, string> {
  Object.assign(target, firstClassOverlayFor(lang));
  return target;
}

export function mergeFirstClassStrings(target: Record<string, string>, lang: string): void {
  applyFirstClassOverlay(target, lang);
}

export function overlayHasKey(lang: UiLang, key: FirstClassKey): boolean {
  const row = firstClassOverlayFor(lang);
  return typeof row[key] === 'string' && row[key].length > 0;
}
