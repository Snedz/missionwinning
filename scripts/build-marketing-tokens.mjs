#!/usr/bin/env node
/**
 * Generate sites/www/src/styles/tokens.css from the app's own :root block.
 *
 * The www surface is a fourth place brand colours could live, and `.178` says
 * one fact has one home. So nobody types a hex into sites/www — this script
 * copies the triplets out of src/index.css, and `check-token-sync.mjs` fails
 * the gate when the committed output drifts from the source.
 *
 * Two shape constraints, both load-bearing, both learned the hard way:
 *
 *  1. Emit bare `--var: H S% L%` triplets, never `hsl(...)`. check-token-sync's
 *     parser accepts only that form — an `hsl()` wrapper is silently skipped and
 *     reads as a missing var, i.e. drift that looks like absence. The same bare
 *     form is what keeps check-design-system's off-palette-colour rule quiet,
 *     since a digit after `(` is what that rule calls a literal.
 *
 *  2. The output is COMMITTED, not built on demand. A generated file that only
 *     exists after a build step is a file CI can forget to regenerate; committing
 *     it means `git diff --exit-code` is the staleness check, and the drift shows
 *     up in review as a diff rather than in production as a wrong red.
 *
 * Run: npm run www:tokens
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const SRC = path.join(root, 'src/index.css');
const OUT = path.join(root, 'sites/www/src/styles/tokens.css');

/**
 * The tokens the marketing surface is allowed to use.
 *
 * An allowlist rather than "copy every var", because src/index.css carries
 * ~40 app-only tokens (meter tracks, ink panels, status hues) whose presence
 * here would invite a marketing page to reach for one. Adding a row is a
 * deliberate act; forgetting to remove one is not possible, because the
 * generator fails on a name it cannot find.
 */
const TOKENS = [
  ['--background', 'paper — the only ground, never pure white'],
  ['--foreground', 'ink'],
  ['--card', 'surface panel'],
  ['--muted-foreground', 'quiet ink — 28% not 37%, see src/index.css'],
  ['--border', 'ALL rules are 2px solid this, never hairlines'],
  ['--primary', 'red text/border #ae1800 — safe at any size'],
  ['--primary-foreground', 'paper on red'],
  ['--primary-fill', 'button fills #dd2b0f — white text 4.74:1 AA'],
  ['--primary-fill-hover', ''],
  ['--accent-poster', 'poster red #ec3013 — fills, chrome, large labels only'],
  ['--accent-tint', 'highlighted rows, tracks'],
  ['--ring', 'focus ring = poster red'],
  ['--radius', 'zero everywhere, on purpose'],
];

function firstRootBlock(css) {
  // src/index.css has two :root blocks (colours at ~10, font aliases at ~108).
  // The colours are in the first — same assumption check-token-sync makes, and
  // it is stated here so the two cannot quietly disagree about which one.
  const m = css.match(/:root\s*\{([^}]+)\}/s);
  if (!m) throw new Error('No :root block found in src/index.css');
  return m[1];
}

function parseTriplets(block) {
  /** @type {Record<string,string>} */
  const out = {};
  for (const line of block.split('\n')) {
    const triplet = line.match(/^\s*(--[\w-]+):\s*([\d.]+\s+[\d.]+%\s+[\d.]+%)\s*;/);
    if (triplet) {
      out[triplet[1]] = triplet[2];
      continue;
    }
    // --radius is a length, not a triplet. Kept because zero radius is as much
    // a brand fact as the reds are, and a marketing page that rounds a corner
    // is off-system in exactly the way check-design-system cannot see in CSS
    // it does not walk.
    const plain = line.match(/^\s*(--radius):\s*([^;]+);/);
    if (plain) out[plain[1]] = plain[2].trim();
  }
  return out;
}

function main() {
  const css = fs.readFileSync(SRC, 'utf8');
  const vars = parseTriplets(firstRootBlock(css));

  const missing = TOKENS.map(([name]) => name).filter((n) => !(n in vars));
  if (missing.length) {
    // Fail loud. A generator that emits a file missing half its tokens produces
    // a site that renders in browser defaults and a token check that passes on
    // what is there — the vacuous-green shape this repo keeps paying for.
    console.error(
      `build-marketing-tokens: ${missing.length} token(s) not found in src/index.css:\n  ` +
        missing.join('\n  ') +
        '\n\nEither the token was renamed (update TOKENS here) or the :root block moved.'
    );
    process.exitCode = 1;
    return;
  }

  const lines = [
    '/* GENERATED by scripts/build-marketing-tokens.mjs — do not edit.',
    ' *',
    ' * Source of truth is src/index.css. Editing this file by hand is drift, and',
    ' * `npm run check-token-sync` fails on it. To change a brand colour, change it',
    ' * in src/index.css and re-run `npm run www:tokens`.',
    ' *',
    ' * Values are bare `H S% L%` triplets because that is the only form',
    ' * check-token-sync parses, and the only form off-palette-colour ignores.',
    ' */',
    ':root {',
  ];
  for (const [name, why] of TOKENS) {
    if (why) lines.push(`  /* ${why} */`);
    lines.push(`  ${name}: ${vars[name]};`);
  }
  lines.push('}', '');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join('\n'));
  console.log(`build-marketing-tokens: wrote ${TOKENS.length} tokens → sites/www/src/styles/tokens.css`);
}

main();
